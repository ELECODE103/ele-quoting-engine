/**
 * Browser security headers.
 *
 * Content-Security-Policy — the strictest policy the built site runs under:
 *
 *   script-src 'self' https://challenges.cloudflare.com
 *       No inline scripts and no eval. The build has neither: one external
 *       module script per page (Vite), lazy chunks from /assets, and JSON-LD
 *       blocks, which are data and are not executed. three.js needs no eval
 *       and nothing here loads WebAssembly in the browser. Cloudflare's host
 *       is for the Turnstile widget on the sign-up and request forms.
 *   script-src-attr 'none'
 *       No onclick="…" attributes anywhere.
 *   style-src-elem 'self' [+ hashes]
 *       Stylesheets come from /assets only. The app's pages have no <style>
 *       blocks. A hand-written static page in client/public that has one is
 *       allowed by the SHA-256 of its block, computed from the built file at
 *       startup (staticStyleHashes) — but only if the site serves that page.
 *       Today none qualifies: the brand guide and its sheets are internal and
 *       answer 404 (seo.js), so the policy carries no hashes.
 *   style-src-attr 'unsafe-inline'
 *       The prerendered pages carry style="…" attributes (React inline
 *       styles written out as HTML). An attribute can restyle its own element
 *       and nothing else; it cannot run script.
 *   font-src 'self'
 *       Fonts are self-hosted (@fontsource); the Google Fonts hosts are gone.
 *       (A served static page whose own hash-allowed CSS embeds fonts as
 *       data: URIs would get data: on its URL only; none is served today.)
 *   img-src 'self' data: blob:
 *       Local images, inline SVG in CSS, and canvas / preview blobs.
 *   connect-src 'self'
 *       The API is same-origin. Stripe is reached by a full-page redirect to
 *       its hosted checkout — no Stripe script, frame or XHR on our pages.
 *   frame-src https://challenges.cloudflare.com
 *       The Turnstile challenge frame; nothing else is framed.
 *   frame-ancestors 'none'   (and X-Frame-Options: DENY)
 *       The site cannot be put in a frame on another site (clickjacking).
 *   object-src 'none', base-uri 'self', form-action 'self'
 *
 * Also set here: Referrer-Policy, Permissions-Policy, HSTS, nosniff, and
 * no-store on API responses.
 *
 * To see what a change would break before enforcing it, set
 * CSP_REPORT_ONLY=true: the policy is then reported in the browser console but
 * not enforced. Leave it unset in production.
 */
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");
const helmet = require("helmet");

const TURNSTILE = "https://challenges.cloudflare.com";

/**
 * CSP hashes for the <style> blocks of the hand-written static pages shipped in
 * client/public (the brand guide). The app's own pages have no <style> blocks;
 * a static page that does is allowed by the exact hash of each block, computed
 * from the built file at startup — so the block that was reviewed and built is
 * the only inline style that will ever apply, and editing the page needs no
 * change here.
 */
function scanStaticPages(distDir) {
  const styleHashes = new Set();
  const dataFontPages = new Set(); // URL paths of static pages whose own CSS embeds its fonts as data: URIs
  const walk = (dir, depth) => {
    let entries;
    try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const e of entries) {
      if (e.name === "_prerender" || e.name === "assets") continue; // generated by the build: no <style> blocks
      const p = path.join(dir, e.name);
      if (e.isDirectory()) { if (depth < 4) walk(p, depth + 1); continue; }
      if (!e.name.endsWith(".html")) continue;
      // A page the live site does not serve (the internal brand sheets: seo.js answers 404 for them)
      // gets no allowance in the policy either.
      if (require("../seo").isInternalBrandPath(`/${path.relative(distDir, p).split(path.sep).join("/")}`)) continue;
      const html = fs.readFileSync(p, "utf8");
      for (const m of html.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)) {
        styleHashes.add(`'sha256-${crypto.createHash("sha256").update(m[1], "utf8").digest("base64")}'`);
        if (/url\(\s*["']?data:(font|application\/(x-)?font)/i.test(m[1])) dataFontPages.add(`/${path.relative(distDir, p).split(path.sep).join("/")}`);
      }
    }
  };
  if (distDir) walk(distDir, 0);
  return { styleHashes: [...styleHashes], dataFontPages };
}
const staticStyleHashes = (distDir) => scanStaticPages(distDir).styleHashes;

function cspDirectives({ styleHashes = [], dataFontPages = new Set() } = {}) {
  return {
    defaultSrc: ["'self'"],
    scriptSrc: ["'self'", TURNSTILE],
    scriptSrcAttr: ["'none'"],
    // style-src is what browsers without -elem/-attr support fall back to.
    styleSrc: ["'self'", "'unsafe-inline'"],
    styleSrcElem: ["'self'", ...styleHashes],
    styleSrcAttr: ["'unsafe-inline'"],
    // Self-hosted fonts. The static brand pages embed theirs in their own (hash-allowed) CSS, so
    // data: is added for exactly those pages and no others.
    fontSrc: ["'self'", ...(dataFontPages.size ? [(req) => (dataFontPages.has(req.path) ? "data:" : "'self'")] : [])],
    imgSrc: ["'self'", "data:", "blob:"],
    connectSrc: ["'self'"],
    frameSrc: [TURNSTILE],
    workerSrc: ["'self'"],
    manifestSrc: ["'self'"],
    mediaSrc: ["'self'"],
    objectSrc: ["'none'"],
    baseUri: ["'self'"],
    formAction: ["'self'"],
    frameAncestors: ["'none'"],
  };
}

// Browser features no page here uses, switched off for the page and anything it embeds.
const PERMISSIONS_POLICY = [
  "accelerometer=()", "autoplay=()", "camera=()", "display-capture=()", "encrypted-media=()", "geolocation=()",
  "gyroscope=()", "magnetometer=()", "microphone=()", "midi=()", "payment=()", "usb=()", "browsing-topics=()",
].join(", ");

/**
 * Mount the header middleware. Call first, before any route.
 * @param {object} [opt]
 * @param {string} [opt.distDir] the built client (client/dist), scanned once for static pages' <style> blocks
 */
function install(app, opt = {}) {
  const scanned = scanStaticPages(opt.distDir);
  app.use(helmet({
    contentSecurityPolicy: {
      useDefaults: false,
      reportOnly: process.env.CSP_REPORT_ONLY === "true",
      directives: {
        ...cspDirectives(scanned),
        // Only meaningful over HTTPS; left out in development so http://localhost keeps working.
        ...(process.env.NODE_ENV === "production" ? { upgradeInsecureRequests: [] } : {}),
      },
    },
    crossOriginEmbedderPolicy: false,
    // Origin only, and only to HTTPS: a firm-quote link (which carries its token in the path)
    // is never sent to another site, while the Turnstile and Stripe hosts still see which site sent the visitor.
    referrerPolicy: { policy: "strict-origin-when-cross-origin" },
    frameguard: { action: "deny" },
    hsts: { maxAge: 31536000, includeSubDomains: true, preload: true },
  }));
  app.use((req, res, next) => {
    res.setHeader("Permissions-Policy", PERMISSIONS_POLICY);
    next();
  });
  // API answers hold quotes, orders and account details: never kept by a browser or a proxy.
  app.use("/api", (req, res, next) => {
    res.setHeader("Cache-Control", "no-store");
    next();
  });
}

module.exports = { install, cspDirectives, scanStaticPages, staticStyleHashes, PERMISSIONS_POLICY };
