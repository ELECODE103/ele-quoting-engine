async function main() {
  if (NO_RENDER) { console.log('kit: wrote SVG / DXF / manifest / guide HTML (render skipped)'); return; }
  await L.withBrowser(async (browser) => {
    for (const j of jobs) await L.renderPng(browser, j);
    // favicon.ico
    const icoPngs = [];
    for (const s of ICO_SIZES) icoPngs.push({ size: s, buf: await L.renderPng(browser, { svg: icoSvg(s), w: s, h: s, transparent: true, out: path.join(B, 'icons', `favicon-${s}.png`) }) });
    write(path.join(PUB, 'favicon.ico'), L.ico(icoPngs));
    // post examples
    const { compositePost } = require('./post');
    for (const ex of POST_EXAMPLES) await compositePost(browser, { ...ex, photo: path.join(PUB, 'photos', ex.photo), out: path.join(SOC, ex.out), domain: brand.domain });
    // brand guide PDF
    const page = await browser.newPage();
    await page.goto(fileUrl(path.join(B, 'brand-guide.html')));
    await page.evaluate(() => document.fonts.ready);
    await page.pdf({ path: path.join(B, 'brand-guide.pdf'), width: '8.5in', height: '11in', printBackground: true, pageRanges: '1' });
    await page.close();
    // documents + contact sheet
    const docPngs = pdfPreviews();
    write(path.join(B, 'kit-sheet.html'), sheetHtml(docPngs));
    const sheet = await browser.newPage({ viewport: { width: 2400, height: 1200 } });
    await sheet.goto(fileUrl(path.join(B, 'kit-sheet.html')));
    await sheet.evaluate(() => document.fonts.ready);
    const height = await sheet.evaluate(() => document.documentElement.scrollHeight);
    if (height > 8000) console.warn(`kit-sheet is ${height}px tall — over the 8000px limit`);
    await sheet.screenshot({ path: path.join(B, 'kit-sheet.png'), fullPage: true });
    await sheet.close();
    console.log(`kit: ${jobs.length} images, favicon.ico, brand-guide.pdf, ${docPngs.length} document previews, kit-sheet.png (2400 × ${height})`);
  });
}
main().catch((e) => { console.error(e); process.exit(1); });
