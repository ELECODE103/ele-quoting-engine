// DXF R12 (AC1009): closed POLYLINEs, millimetres, Y up, origin at the lower-left corner of the
// square. R12 is the dialect every laser, engraver and router package reads.
function dxf(polys, sizeMm) {
  const k = sizeMm / 100, f = (n) => (Math.round(n * 10000) / 10000).toString();
  const out = ['0', 'SECTION', '2', 'HEADER', '9', '$ACADVER', '1', 'AC1009', '9', '$INSUNITS', '70', '4', '9', '$MEASUREMENT', '70', '1',
    '9', '$EXTMIN', '10', '0', '20', '0', '9', '$EXTMAX', '10', f(sizeMm), '20', f(sizeMm), '0', 'ENDSEC',
    '0', 'SECTION', '2', 'TABLES',
    '0', 'TABLE', '2', 'LTYPE', '70', '1', '0', 'LTYPE', '2', 'CONTINUOUS', '70', '0', '3', 'Solid line', '72', '65', '73', '0', '40', '0.0', '0', 'ENDTAB',
    '0', 'TABLE', '2', 'LAYER', '70', '1', '0', 'LAYER', '2', 'MARK', '70', '0', '62', '7', '6', 'CONTINUOUS', '0', 'ENDTAB',
    '0', 'ENDSEC', '0', 'SECTION', '2', 'ENTITIES'];
  for (const p of polys) {
    out.push('0', 'POLYLINE', '8', 'MARK', '66', '1', '70', '1', '10', '0', '20', '0', '30', '0');
    for (const [x, y] of p) out.push('0', 'VERTEX', '8', 'MARK', '10', f(x * k), '20', f((100 - y) * k), '30', '0');
    out.push('0', 'SEQEND', '8', 'MARK');
  }
  out.push('0', 'ENDSEC', '0', 'EOF');
  return out.join('\r\n') + '\r\n';
}
