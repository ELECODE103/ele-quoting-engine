function hero(w, h, { headline, sub, lines }) {
  const k = h / 630, m = 80 * k, inner = w - 2 * m;
  const S = 72 * k;
  const body = [
    `<rect width="${w}" height="${h}" fill="${INK}"/>`,
    L.lightBand(w - 250 * k, h - 60 * k, 1100 * k),
    lockup(m, m * 0.9, S, { markFill: BONE, wordFill: BONE }).markup,
    `<rect x="${r(m)}" y="${r(m * 0.9 + S + 40 * k)}" width="${r(inner)}" height="${Math.max(2, r(2 * k))}" fill="${BRASS}"/>`,
  ];
  if (lines) {
    // two-line statement, both lines at one size
    const size = Math.min(...lines.map((s) => txt('archivo-700', s, 72 * k, { maxWidth: inner }).size));
    body.push(txt('archivo-700', lines[0], size, { x: m, y: 345 * k, fill: BONE }).markup);
    body.push(txt('archivo-700', lines[1], size, { x: m, y: 345 * k + size * 1.22, fill: MUTED }).markup);
  } else {
    body.push(txt('archivo-700', headline, 104 * k, { x: m, y: 368 * k, fill: BONE, maxWidth: inner }).markup);
    body.push(txt('inter-500', sub, 36 * k, { x: m, y: 440 * k, fill: MUTED, maxWidth: inner }).markup);
  }
  const dom = txt('inter-600', brand.domain, 26 * k, { x: m, y: h - m * 0.85, fill: BONE });
  body.push(dom.markup);
  body.push(txt('inter-500', PLACE, 26 * k, { x: m + dom.width + 28 * k, y: h - m * 0.85, fill: MUTED }).markup);
  return body.join('\n');
}
