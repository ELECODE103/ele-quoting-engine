#!/usr/bin/env node
/**
 * Writes client/src/data/catalog.generated.json from server/config/defaults.js.
 *
 * The public pages (materials table, /materials/:slug, the prerendered HTML and
 * the sitemap) need to know which materials the shop quotes and in which stock
 * forms / thicknesses, at build time and without an API call. This copies ONLY
 * the public, non-commercial fields - no prices, waste factors or machinability
 * numbers leave the server.
 *
 * Runs as the first step of `npm run build`. The output is committed so `vite`
 * dev works without it; `--check` (used by the test suite) fails when the
 * committed file is stale.
 */
const fs = require("fs");
const path = require("path");
const { CNC_MATERIALS, ROUTING_MATERIALS, PRINTING_MATERIALS } = require("../../server/config/defaults");

const OUT = path.join(__dirname, "..", "..", "client", "src", "data", "catalog.generated.json");

function pub(m) {
  return {
    slug: m.slug,
    name: m.name,
    category: m.category,
    process: m.process,
    subProcess: m.subProcess || "",
    grades: (m.grades || []).map((g) => ({ name: g.name })),
    stockForms: m.stockForms || [],
    thicknesses: (m.thicknesses || []).map((t) => ({ label: t.label, inch: t.inch, mm: t.mm })),
    color: m.color || "",
  };
}

function build() {
  const active = (list) => list.filter((m) => m.active).map(pub);
  return {
    _comment: "GENERATED by scripts/seo/gen-catalog.js from server/config/defaults.js. Do not edit.",
    cnc: active(CNC_MATERIALS),
    routing: active(ROUTING_MATERIALS),
    printing: active(PRINTING_MATERIALS),
  };
}

const json = JSON.stringify(build(), null, 2) + "\n";
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== json) {
    console.error("catalog.generated.json is stale. Run: node scripts/seo/gen-catalog.js");
    process.exit(1);
  }
  console.log("catalog.generated.json is up to date");
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, json);
  console.log(`catalog: wrote ${path.relative(process.cwd(), OUT)}`);
}
